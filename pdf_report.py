from fpdf import FPDF


# Helper to prevent FPDF font encoding errors on special characters (em-dashes, smart quotes, etc.)
def clean_text(text: str) -> str:
    if not text:
        return "None"
    replacements = {
        "\u2013": "-",
        "\u2014": "--",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2022": "*",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


class AuditReportPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(100, 116, 139)  # Slate gray
        self.cell(
            0,
            8,
            "METASCIENCE CLAIM-TO-EVIDENCE AUDIT REPORT",
            align="R",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        self.set_draw_color(226, 232, 240)
        self.line(10, 18, 200, 18)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(
            0,
            10,
            f"Generated by Claim-to-Evidence Transparency Auditor | Page {self.page_no()}",
            align="C",
        )


def get_status_colors(status: str):
    """Returns (R, G, B) badge color based on evidence status."""
    palette = {
        "STRONG_INTERNAL": (22, 163, 74),  # Green
        "EXTERNAL_CITATION": (37, 99, 235),  # Blue
        "UNCLEAR_OR_AMBIGUOUS": (217, 119, 6),  # Amber
        "UNSUPPORTED": (220, 38, 38),  # Red
    }
    return palette.get(status, (71, 85, 105))


def generate_audit_pdf(audit_data: dict, output_path: str = "audit_report.pdf"):
    """
    Takes the parsed JSON dictionary from the LLM audit and builds a styled PDF report.
    """
    pdf = AuditReportPDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    # --- 1. Paper Title ---
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 23, 42)  # Dark navy
    pdf.multi_cell(
        0,
        9,
        clean_text(audit_data.get("paper_title", "Untitled Paper")),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(3)

    # --- 2. Overall Rigor Score Banner ---
    score = audit_data.get("overall_rigor_score", 0)
    if score >= 8:
        score_color = (22, 163, 74)  # Green
        rating_label = "STRONGLY EVIDENCE-BASED"
    elif score >= 5:
        score_color = (217, 119, 6)  # Amber
        rating_label = "MODERATE / MIXED RIGOR"
    else:
        score_color = (220, 38, 38)  # Red
        rating_label = "LOW RIGOR / SPECULATIVE"

    pdf.set_fill_color(*score_color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(
        0,
        11,
        f"  OVERALL RIGOR SCORE: {score} / 10  ({rating_label})",
        fill=True,
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(4)

    # --- 3. Executive Summary Box ---
    pdf.set_fill_color(248, 250, 252)  # Light slate background
    pdf.set_text_color(30, 41, 59)
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 7, "Executive Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.multi_cell(
        0,
        6,
        clean_text(audit_data.get("executive_summary", "")),
        fill=True,
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(6)

    # --- 4. Claim-by-Claim Breakdown ---
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(15, 23, 42)
    claims = audit_data.get("claims", [])
    pdf.cell(
        0,
        8,
        f"Claim-to-Evidence Breakdown ({len(claims)} Core Claims Audited)",
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(2)

    for claim in claims:
        status = claim.get("evidence_status", "UNKNOWN")
        r, g, b = get_status_colors(status)

        # Claim Header + Status Badge
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(15, 23, 42)
        claim_header = f"[{claim.get('id', 'C?')}] Location: {clean_text(claim.get('claim_location', 'N/A'))}"
        pdf.cell(125, 7, claim_header)

        pdf.set_fill_color(r, g, b)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(65, 7, status, align="C", fill=True, new_x="LMARGIN", new_y="NEXT")

        # Claim Text
        pdf.set_text_color(15, 23, 42)
        pdf.set_font("Helvetica", "B", 10)
        pdf.multi_cell(
            0,
            5.5,
            f"Claim: {clean_text(claim.get('claim_text', ''))}",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        pdf.ln(1)

        # Evidence Quote & Location
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(51, 65, 85)
        ev_loc = clean_text(claim.get("evidence_location", "None"))
        ev_quote = clean_text(claim.get("evidence_quote", "None found"))
        pdf.multi_cell(
            0, 5, f'Evidence ({ev_loc}): "{ev_quote}"', new_x="LMARGIN", new_y="NEXT"
        )
        pdf.ln(1)

        # Auditor Note
        pdf.set_font("Helvetica", "I", 9.5)
        pdf.set_text_color(71, 85, 105)
        pdf.multi_cell(
            0,
            5,
            f"Audit Note: {clean_text(claim.get('audit_note', ''))}",
            new_x="LMARGIN",
            new_y="NEXT",
        )

        # Divider line between claims
        pdf.ln(2)
        pdf.set_draw_color(226, 232, 240)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(4)

    pdf.output(output_path)
    print(f"PDF report successfully saved to: {output_path}")
